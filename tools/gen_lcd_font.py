def rows(c):
    return [sum(1 << (4 - i) for i, ch in enumerate(r) if ch == "#") for r in G[c].split()]


def main():
    if sys.argv[1:2] == ["--png"]:
        from PIL import Image, ImageDraw
        cs = [chr(c) for c in range(32, 96)]
        im = Image.new("RGB", (16 * 14 + 4, 4 * 18 + 4), (150, 168, 64))
        d = ImageDraw.Draw(im)
        for k, c in enumerate(cs):
            x0, y0 = 4 + (k % 16) * 14, 4 + (k // 16) * 18
            for y, r in enumerate(rows(c)):
                for x in range(5):
                    if r >> (4 - x) & 1:
                        d.rectangle((x0 + 2 * x, y0 + 2 * y, x0 + 2 * x + 1, y0 + 2 * y + 1), fill=(30, 40, 20))
        im.resize((im.width * 3, im.height * 3), Image.NEAREST).save(sys.argv[2])
        return
    lines = ["/* generated by tools/gen_lcd_font.py: the LCD's 5 x 7 characters, ASCII 32..95, bit 4 the left column */",
             "#pragma once", "#include <stdint.h>", "static const uint8_t LCD_FONT[64][7] = {"]
    for c in range(32, 96):
        lines.append("    {" + ", ".join(f"0x{v:02X}" for v in rows(chr(c))) + f"}},   /* {chr(c)!r} */")
    lines.append("};")
    open(sys.argv[1], "w").write("\n".join(lines) + "\n")
    print(f"lcd font: 64 characters -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
