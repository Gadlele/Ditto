"""Ditto's name as the power-on draws it: DITTO in wide, squared, heavy letters (the eighties' nameplates, after the
lettering of the instrument it follows), drawn here as shapes 8x over and brought down to an anti-aliased 4-bit
coverage map: LOGO_W x LOGO_H, two pixels a byte (the left one in the low nibble).
  gen_logo.py OUT.h          (tools/build.py)
  gen_logo.py --png OUT.png  a picture of it"""
import sys

from PIL import Image, ImageDraw

S = 8                           # drawn S times over, then reduced
H, W, T = 30, 38, 9             # a letter's height, a wide letter's width, the stroke
GAP = 0.22 * W                  # between letters
R = H * 0.32                    # the corners' radius


def logo():
    width = int(round(W * 4 + T + GAP * 4)) + 2
    im = Image.new("L", (width * S, (H + 2) * S), 0)
    d = ImageDraw.Draw(im)

    def rr(box, r, fill):
        d.rounded_rectangle([v * S for v in box], radius=r * S, fill=fill)

    def rect(box, fill):
        d.rectangle([v * S for v in box], fill=fill)

    y, x = 1, 1.0

    def ring(x):                # O: a rounded square ring; D: the same, its left side square
        rr((x, y, x + W, y + H), R, 255)
        rr((x + T, y + T, x + W - T, y + H - T), R - T * 0.9, 0)

    ring(x)                     # D
    rect((x, y, x + W * 0.35, y + H), 255)
    rect((x + T, y + T, x + W * 0.4, y + H - T), 0)
    x += W + GAP
    rect((x, y, x + T, y + H), 255)                                     # I
    x += T + GAP
    for _ in range(2):                                                   # T T
        rect((x, y, x + W, y + T), 255)
        rect((x + W / 2 - T / 2, y, x + W / 2 + T / 2, y + H), 255)
        x += W + GAP
    ring(x)                                                              # O
    return im.resize((width, H + 2), Image.LANCZOS)


def main():
    im = logo()
    if sys.argv[1:2] == ["--png"]:
        im.save(sys.argv[2])
        return
    w, h = im.size
    px = im.load()
    data = []
    for yy in range(h):
        for xx in range(0, w, 2):
            a = px[xx, yy] * 15 // 255
            b = px[xx + 1, yy] * 15 // 255 if xx + 1 < w else 0
            data.append(a | b << 4)
    lines = ["/* generated by tools/gen_logo.py: DITTO, the power-on's name, 4-bit coverage, two pixels a byte */",
             "#pragma once", "#include <stdint.h>", f"#define LOGO_W {w}", f"#define LOGO_H {h}",
             f"static const uint8_t LOGO[{len(data)}] = {{"]
    for i in range(0, len(data), 32):
        lines.append("    " + ",".join(map(str, data[i:i + 32])) + ",")
    lines.append("};")
    open(sys.argv[1], "w").write("\n".join(lines) + "\n")
    print(f"logo: {w} x {h}, {len(data)} B -> {sys.argv[1]}")


if __name__ == "__main__":
    main()
